function normalizeTitleKey(value) {
  return String(value ?? '')
    .normalize('NFKC')
    .replace(/\s+/g, '')
    .replace(/[：:·,，.。()（）《》【】[\]\-—_/]/g, '')
    .toLowerCase();
}

export function resolveEntryCover(entry) {
  if (!entry) return { poster: '', still: '' };
  const cover =
    coverByEntryId[entry.id] ??
    coverByNormalizedTitle[normalizeTitleKey(entry.title)] ??
    {};
  return {
    still: entry.still || cover.still || '',
    poster: entry.poster || cover.poster || '',
  };
}
